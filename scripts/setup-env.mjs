#!/usr/bin/env node
// Creates .env.local with freshly generated secrets for local development.
// Never overwrites an existing file.
import fs from "node:fs";
import crypto from "node:crypto";

const target = ".env.local";
if (fs.existsSync(target)) {
  console.log(`${target} already exists; leaving it unchanged.`);
  process.exit(0);
}
const rand = (n) => crypto.randomBytes(n).toString("base64url");
const accessKey = rand(24);
const content = `# Generated by \`npm run setup\` for LOCAL DEVELOPMENT. Do not commit.
APP_URL=http://localhost:3000
APP_SECRET=${rand(48)}
EDITOR_ACCESS_KEY=${accessKey}
EDITOR_DISPLAY_NAME=Editor

# Leave DATABASE_URL unset to use embedded PGlite (local development mode).
# DATABASE_URL=postgresql://...

# Leave S3_* unset to use local filesystem storage (local development mode).
# R2_ACCOUNT_ID=
# S3_BUCKET=
# S3_ACCESS_KEY_ID=
# S3_SECRET_ACCESS_KEY=

# GEMINI_API_KEY=
# GEMINI_MODEL=gemini-2.5-flash
`;
fs.writeFileSync(target, content, { mode: 0o600 });
console.log(`Created ${target}.`);
console.log("Your editor access key is stored in .env.local as EDITOR_ACCESS_KEY. Use it on the /unlock page.");
