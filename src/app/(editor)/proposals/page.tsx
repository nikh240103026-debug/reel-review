import Link from "next/link";
import { Sparkles } from "lucide-react";
import { PageHeader } from "@/components/app-shell";
import { EmptyState, Pill, StatusBadge } from "@/components/status";
import { listProposals } from "@/lib/services/proposals";
import { timeAgo } from "@/lib/format";
import { ADAPTERS, type AdapterId } from "@/shared/operations";

export const metadata = { title: "Approvals" };

export default async function ProposalsPage() {
  const proposals = await listProposals({ limit: 100 });
  const needsYou = proposals.filter((p) => ["awaiting_approval", "needs_clarification", "approved"].includes(p.status));
  const rest = proposals.filter((p) => !needsYou.includes(p));

  const table = (items: typeof proposals) => (
    <div className="overflow-x-auto rounded-lg border bg-card">
      <table className="w-full min-w-[720px] text-[13px]">
        <thead className="border-b text-left text-xs text-muted-foreground">
          <tr>
            <th className="px-4 py-2 font-normal">Video</th>
            <th className="px-4 py-2 font-normal">Revision</th>
            <th className="px-4 py-2 font-normal">Operations</th>
            <th className="px-4 py-2 font-normal">Adapter</th>
            <th className="px-4 py-2 font-normal">Generated by</th>
            <th className="px-4 py-2 font-normal">Status</th>
            <th className="px-4 py-2 font-normal">Created</th>
          </tr>
        </thead>
        <tbody className="divide-y">
          {items.map((p) => (
            <tr key={p.id} className="hover:bg-subtle">
              <td className="px-4 py-2.5">
                <Link href={`/proposals/${p.id}`} className="font-medium hover:underline">
                  {p.video_title}
                </Link>
                <div className="text-xs text-muted-foreground">
                  {p.project_name} · source v{p.source_version_number}
                </div>
              </td>
              <td className="px-4 py-2.5 tabular">{p.revision}</td>
              <td className="px-4 py-2.5 text-xs text-muted-foreground tabular">
                {p.op_counts?.approved}/{p.op_counts?.total} approved
              </td>
              <td className="px-4 py-2.5 text-xs">{ADAPTERS[p.adapter as AdapterId]?.label ?? p.adapter}</td>
              <td className="px-4 py-2.5 text-xs">
                {p.generator === "gemini" ? "Gemini" : p.generator === "claude" ? "Claude" : <Pill tone="warning">Offline · not AI</Pill>}
              </td>
              <td className="px-4 py-2.5">
                <StatusBadge status={p.status} />
              </td>
              <td className="px-4 py-2.5 text-xs text-muted-foreground">{timeAgo(p.created_at)}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );

  return (
    <>
      <PageHeader title="Approvals" description="Every AI-generated edit proposal must be reviewed and approved here before anything can run." />
      <div className="space-y-8 px-4 py-6 sm:px-6">
        {proposals.length === 0 ? (
          <EmptyState icon={Sparkles} title="No proposals yet" description="Open a video and press AI Review to analyze unresolved client comments." />
        ) : (
          <>
            <div>
              <h2 className="mb-3 text-sm font-medium">Needs your attention</h2>
              {needsYou.length ? table(needsYou) : <p className="text-sm text-muted-foreground">Nothing waiting on you.</p>}
            </div>
            {rest.length > 0 && (
              <div>
                <h2 className="mb-3 text-sm font-medium">History</h2>
                {table(rest)}
              </div>
            )}
          </>
        )}
      </div>
    </>
  );
}
